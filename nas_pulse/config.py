"""Configuration loader and manager for NAS-Pulse."""

from __future__ import annotations

import os
from pathlib import Path
from typing import Optional
from dotenv import load_dotenv

CONFIG_DIR = Path.home() / ".config" / "nas-pulse"
DEFAULT_USER_CONFIG = CONFIG_DIR / ".env"

class Config:
    def __init__(self, env_path: Optional[str | Path] = None):
        self.loaded_path: Optional[Path] = None
        
        # 1. Check explicit path
        if env_path:
            p = Path(env_path).expanduser().resolve()
            if p.is_file():
                load_dotenv(p, override=True)
                self.loaded_path = p
        
        # 2. Check local .env
        if not self.loaded_path:
            local_env = Path(".env").resolve()
            if local_env.is_file():
                load_dotenv(local_env, override=False)
                self.loaded_path = local_env

        # 3. Check user config directory (~/.config/nas-pulse/.env)
        if not self.loaded_path and DEFAULT_USER_CONFIG.is_file():
            load_dotenv(DEFAULT_USER_CONFIG, override=False)
            self.loaded_path = DEFAULT_USER_CONFIG

        # Load values with defaults
        self.nas_ip: str = os.getenv("NAS_IP", "").strip()
        self.nas_port: int = int(os.getenv("NAS_PORT", "5001"))
        self.nas_user: str = os.getenv("NAS_USER", "").strip()
        self.nas_password: str = os.getenv("NAS_PASSWORD", "")
        self.nas_secure: bool = os.getenv("NAS_SECURE", "True").lower() in ("true", "1", "yes")
        self.nas_cert_verify: bool = os.getenv("NAS_CERT_VERIFY", "False").lower() in ("true", "1", "yes")
        self.nas_dsm_version: int = int(os.getenv("NAS_DSM_VERSION", "7"))

        # Portainer settings (optional)
        self.portainer_url: str = os.getenv("PORTAINER_URL", "").rstrip("/")
        # Accept either PORTAINER_AUDIT_TOKEN or PORTAINER_TOKEN
        self.portainer_token: str = (
            os.getenv("PORTAINER_AUDIT_TOKEN") or os.getenv("PORTAINER_TOKEN") or ""
        ).strip()

    @property
    def is_configured(self) -> bool:
        """Returns True if the minimal Synology connection parameters exist."""
        return bool(self.nas_ip and self.nas_user and self.nas_password)

    @property
    def has_portainer(self) -> bool:
        """Returns True if Portainer URL and Token are set."""
        return bool(self.portainer_url and self.portainer_token)

    def validate(self) -> list[str]:
        """Validate required fields, returns list of missing parameters."""
        missing = []
        if not self.nas_ip:
            missing.append("NAS_IP (e.g. 192.168.1.100)")
        if not self.nas_user:
            missing.append("NAS_USER")
        if not self.nas_password:
            missing.append("NAS_PASSWORD")
        return missing

    @classmethod
    def save(
        cls,
        dest_path: Path,
        nas_ip: str,
        nas_port: int,
        nas_user: str,
        nas_password: str,
        nas_secure: bool = True,
        nas_cert_verify: bool = False,
        nas_dsm_version: int = 7,
        portainer_url: str = "",
        portainer_token: str = "",
    ) -> None:
        """Save configuration to file with safe permission 0600."""
        dest_path.parent.mkdir(parents=True, exist_ok=True)
        content = [
            "# Auto-generated by nas-pulse setup",
            f"NAS_IP={nas_ip}",
            f"NAS_PORT={nas_port}",
            f"NAS_USER={nas_user}",
            f"NAS_PASSWORD={nas_password}",
            f"NAS_SECURE={'True' if nas_secure else 'False'}",
            f"NAS_CERT_VERIFY={'True' if nas_cert_verify else 'False'}",
            f"NAS_DSM_VERSION={nas_dsm_version}",
        ]
        if portainer_url:
            content.append(f"PORTAINER_URL={portainer_url}")
        if portainer_token:
            content.append(f"PORTAINER_TOKEN={portainer_token}")

        dest_path.write_text("\n".join(content) + "\n", encoding="utf-8")
        try:
            dest_path.chmod(0o600)
        except OSError:
            pass
